"""Build the GRSL figures and tables from tracked results.

Run from any directory with Python, numpy, matplotlib, and Pillow:
    python3 scripts/06_figures/make_grsl_figures.py

Qualitative panels are embedded unchanged. No prediction is redrawn or inferred
from a screenshot. Historical result files are inputs, never overwritten.
"""

import csv
import itertools
import json
import re
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from grsl_style import COLUMN, PALETTE, WIDE, save, use_style
from matplotlib.lines import Line2D
from matplotlib.patches import FancyArrowPatch
from PIL import Image

use_style()

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "scripts/results"
FIGURES = ROOT / "figures"
TABLES = ROOT / "tables"
COUNTRIES = (
    "belgium",
    "cambodia",
    "croatia",
    "germany",
    "latvia",
    "lithuania",
    "portugal",
    "slovenia",
    "south_africa",
    "sweden",
)
BLUE, ORANGE = PALETTE["blue"], PALETTE["red"]


def read_results() -> tuple[dict, dict, dict]:
    """Require one finite result for every country and strategy."""
    with (RESULTS / "ensemble_per_country.csv").open() as handle:
        rows = list(csv.DictReader(handle))
    grouped = {}
    for row in rows:
        key = row["strategy"]
        country = row["country"]
        if country in grouped.setdefault(key, {}):
            raise ValueError(f"Duplicate result: {key}, {country}")
        if not all(0 <= float(row[m]) <= 1 for m in ("pq", "sq", "rq")):
            raise ValueError(f"Invalid metric: {row}")
        grouped[key][country] = row
    for key, countries in grouped.items():
        if set(countries) != set(COUNTRIES):
            raise ValueError(f"Incomplete Dense-10 results: {key}")
    for country in COUNTRIES:
        counts = {
            int(grouped[key][country]["n_patches"])
            for key in ("A_nms_pool", "C_pixel_vote", "D_elbow")
        }
        if len(counts) != 1:
            raise ValueError(f"Aggregation patch counts differ: {country}")

    text = (RESULTS / "HEADLINE_ensemble_macro.txt").read_text()
    matches = re.findall(
        r"^\s+(\w+)\s+(0\.\d+)\s+(0\.\d+)\s+[+-]0\.\d+\s*$",
        text,
        re.MULTILINE,
    )
    baseline = {c: float(b) for c, b, _ in matches if c in COUNTRIES}
    if set(baseline) != set(COUNTRIES):
        raise ValueError("Incomplete single-depth headline results")
    for country, _, vote in matches:
        if country in COUNTRIES:
            recorded = float(grouped["C_pixel_vote"][country]["pq"])
            if abs(recorded - float(vote)) > 0.000051:
                raise ValueError(f"Headline and CSV disagree: {country}")

    with (RESULTS / "vector_gt_rescore.csv").open() as handle:
        vector_rows = list(csv.DictReader(handle))
    vector = {row["country"]: row for row in vector_rows}
    if len(vector_rows) != 10 or set(vector) != set(COUNTRIES):
        raise ValueError("Incomplete vector-reference results")
    if any(int(row["skipped"]) for row in vector_rows):
        raise ValueError("Vector-reference rescore skipped patches")
    return grouped, baseline, vector


def macro(rows: dict, key: str) -> float:
    return 100 * np.mean([float(rows[c][key]) for c in COUNTRIES])


def write_rows(filename: str, command: str, rows: list[str]) -> None:
    """Define expandable table rows, so booktabs can follow the last row."""
    body = " \\\\\n".join(rows) + " \\\\\n"
    (TABLES / filename).write_text(
        rf"\newcommand{{\{command}}}{{%" + "\n" + body + "}\n"
    )


def write_tables(grouped: dict, baseline: dict, vector: dict) -> None:
    """Export displayed numbers and a compact provenance summary."""
    TABLES.mkdir(exist_ok=True)
    fv = grouped["C_pixel_vote"]
    base = 100 * np.mean(list(baseline.values()))
    score = macro(fv, "pq")
    delta = np.array([100 * (float(fv[c]["pq"]) - baseline[c]) for c in COUNTRIES])
    # Country bootstrap, not an estimate of model-seed uncertainty.
    rng = np.random.default_rng(0)
    ci = np.quantile(rng.choice(delta, (100_000, 10)).mean(axis=1), [0.025, 0.975])
    # Exact two-sided Wilcoxon signed-rank test; these ten effects have no ties.
    order = np.argsort(abs(delta))
    ranks = np.empty(10, dtype=int)
    ranks[order] = np.arange(1, 11)
    observed = min(ranks[delta > 0].sum(), ranks[delta < 0].sum())
    sums = [np.dot(signs, ranks) for signs in itertools.product((0, 1), repeat=10)]
    pvalue = min(1.0, 2 * np.mean(np.array(sums) <= observed))
    values = {
        "BasePQ": base,
        "VotePQ": score,
        "GainPQ": score - base,
        "VectorBasePQ": macro(vector, "tw_pq"),
        "VectorVotePQ": macro(vector, "fv_pq"),
        "GainLow": ci[0],
        "GainHigh": ci[1],
    }
    lines = ["% Generated by scripts/06_figures/make_grsl_figures.py."]
    lines += [rf"\newcommand{{\{key}}}{{{value:.1f}}}" for key, value in values.items()]
    lines += [rf"\newcommand{{\CountryPValue}}{{{pvalue:.3f}}}"]
    (TABLES / "grsl_values.tex").write_text("\n".join(lines) + "\n")

    main_rows = [
        f"Country-selected watershed & yes & {base:.1f} & {values['VectorBasePQ']:.1f}",
        (
            rf"\textbf{{FieldVote}} & no & \textbf{{{score:.1f}}} & "
            rf"\textbf{{{values['VectorVotePQ']:.1f}}}"
        ),
    ]
    write_rows("grsl_main_rows.tex", "GrslMainRows", main_rows)
    ablation = []
    for key, label in [
        ("A_nms_pool", "Polygon pooling + NMS"),
        ("D_elbow", "Count-based depth selection"),
        ("C_pixel_vote", r"\textbf{Pixel vote (FieldVote)}"),
    ]:
        cells = [f"{macro(grouped[key], metric):.1f}" for metric in ("pq", "sq", "rq")]
        if key == "C_pixel_vote":
            cells = [rf"\textbf{{{cell}}}" for cell in cells]
        ablation.append(label + " & " + " & ".join(cells))
    write_rows("grsl_aggregation_rows.tex", "GrslAggregationRows", ablation)
    summary = {
        "sources": [
            str(p.relative_to(ROOT))
            for p in (
                RESULTS / "ensemble_per_country.csv",
                RESULTS / "HEADLINE_ensemble_macro.txt",
                RESULTS / "vector_gt_rescore.csv",
            )
        ],
        "values": {key: float(value) for key, value in values.items()},
        "wilcoxon_two_sided": float(pvalue),
        "bootstrap": {"unit": "country", "replicates": 100000, "seed": 0},
        "patches": sum(int(row["n_patches"]) for row in fv.values()),
        "countries_improved": int((delta > 0).sum()),
        "oracle_patches": sum(
            int(row["n_patches"]) for row in grouped["B_oracle"].values()
        ),
        "effective_depths": "Not recorded in the tracked result exports.",
    }
    (TABLES / "grsl_summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2))


def panel(fig, name: str, x: float, y: float, w: float, h: float) -> None:
    """Place a complete source image at its original aspect ratio."""
    ax = fig.add_axes([x, y, w, h])
    ax.imshow(Image.open(FIGURES / name), interpolation="none")
    ax.set_axis_off()


def pipeline() -> None:
    fig = plt.figure(figsize=(WIDE, 2.05))
    xs = [0.004, 0.151, 0.345, 0.493, 0.691, 0.851]
    names = ["input", "prob", "wslow", "wshigh", "consensus", "gt"]
    labels = [
        "Image",
        "Probabilities",
        "Shallow depth",
        "Deep depth",
        "FieldVote",
        "Annotation",
    ]
    for x, name, label in zip(xs, names, labels):
        panel(fig, f"fig_pipe_{name}.png", x, 0.14, 0.135, 0.68)
        fig.text(x + 0.0675, 0.065, label, ha="center", va="center", fontsize=8)
    for left, right, label, color in [
        (0.004, 0.286, "(a) Frozen prediction", "#454545"),
        (0.345, 0.628, "(b) Watershed sweep", BLUE),
        (0.691, 0.826, "(c) Pixel vote", ORANGE),
        (0.851, 0.986, "(d) Reference", "#454545"),
    ]:
        fig.text(
            (left + right) / 2,
            0.95,
            label,
            ha="center",
            va="center",
            fontsize=8,
            color=color,
            weight="bold",
        )
        fig.add_artist(
            Line2D(
                [left, right],
                [0.88, 0.88],
                transform=fig.transFigure,
                color=color,
                linewidth=1.2,
            )
        )
    for start, end in [(0.29, 0.336), (0.632, 0.684)]:
        fig.add_artist(
            FancyArrowPatch(
                (start, 0.49),
                (end, 0.49),
                transform=fig.transFigure,
                arrowstyle="-|>",
                mutation_scale=10,
                color="#454545",
                linewidth=1,
            )
        )
    save(fig, str(FIGURES / "grsl_pipeline"))


def country_comparison(grouped: dict, baseline: dict) -> None:
    fv = grouped["C_pixel_vote"]
    ordered = sorted(
        COUNTRIES, key=lambda c: float(fv[c]["pq"]) - baseline[c], reverse=True
    )
    fig = plt.figure(figsize=(COLUMN, 3.0))
    ax = fig.add_axes([0.29, 0.15, 0.57, 0.72])
    for i, country in enumerate(ordered):
        b, v = 100 * baseline[country], 100 * float(fv[country]["pq"])
        ax.plot([b, v], [i, i], color="#929292", linewidth=1.2, zorder=1)
        ax.plot(b, i, "o", color=BLUE, markersize=4, zorder=3)
        ax.plot(v, i, "s", color=ORANGE, markersize=4, zorder=2)
        ax.text(
            1.05,
            i,
            f"{v - b:+.1f}",
            transform=ax.get_yaxis_transform(),
            va="center",
            ha="left",
            fontsize=7.5,
            clip_on=False,
        )
    ax.set_yticks(range(10), [c.replace("_", " ").title() for c in ordered])
    ax.set_ylim(9.5, -0.5)
    ax.set_xlim(0, 58)
    ax.set_xticks([0, 10, 20, 30, 40, 50])
    ax.set_xlabel("Panoptic quality (0-100)")
    ax.grid(axis="x", visible=True)
    ax.grid(axis="y", visible=False)
    ax.tick_params(axis="y", length=0)
    ax.spines["left"].set_visible(False)
    fig.text(0.91, 0.90, "Gain", ha="center", fontsize=7.5)
    handles = [
        Line2D(
            [],
            [],
            color=BLUE,
            marker="o",
            linestyle="none",
            label="Country-selected WS",
        ),
        Line2D([], [], color=ORANGE, marker="s", linestyle="none", label="FieldVote"),
    ]
    fig.legend(
        handles=handles,
        loc="upper center",
        bbox_to_anchor=(0.49, 1.0),
        ncol=2,
        columnspacing=0.7,
        handletextpad=0.3,
    )
    save(fig, str(FIGURES / "grsl_countries"))


def qualitative() -> None:
    fig = plt.figure(figsize=(WIDE, 2.55))
    for group, (country, title) in enumerate(
        [("lt", "(a) Lithuania"), ("hr", "(b) Croatia")]
    ):
        left = 0.008 + group * 0.508
        fig.text(left + 0.232, 0.965, title, ha="center", va="center", weight="bold")
        for col, (suffix, label) in enumerate(
            [
                ("single", "Single depth"),
                ("fv", "FieldVote"),
                ("gt", "Annotation"),
            ]
        ):
            x = left + col * 0.158
            panel(fig, f"fig_res_{country}_{suffix}.png", x, 0.10, 0.149, 0.77)
            fig.text(x + 0.0745, 0.04, label, ha="center", va="center")
    save(fig, str(FIGURES / "grsl_qualitative"))


def main() -> None:
    grouped, baseline, vector = read_results()
    write_tables(grouped, baseline, vector)
    pipeline()
    country_comparison(grouped, baseline)
    qualitative()


if __name__ == "__main__":
    main()
